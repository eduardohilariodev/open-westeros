// Pull every sentence about roads / routes / travel distances out of the scraped blog posts into docs/sources/atlas-blog/_roads.md,
// grouped by post, so road names, endpoints and mileages can be read in one place.
// Usage: node tools/blog/roads-text.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const DIR = 'docs/sources/atlas-blog';
const ROAD = /\b(roads?|kingsroad|king's road|causeway|highway|trail|track|pass|bridge|ford|ferry|route|stairs?|gate)\b/i;
const DIST = /\b\d[\d,.]*\s*(?:-|to\s*\d[\d,.]*\s*)?(miles?|leagues?|days?|hours?|km|kilometres?)\b|\b(day|days|week|weeks|hour|league|leagues|mile|miles)'?s?\s+(ride|march|journey|travel|sail|walk)/i;
const out = ['# Road and distance sentences from the blog (generated by tools/blog/roads-text.mjs)\n'];
let hits = 0;
for (const f of readdirSync(DIR).filter((f) => /^\d.*\.md$/.test(f)).sort()) {
  const text = readFileSync(`${DIR}/${f}`, 'utf8').split('---').slice(2).join('---')
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1'); // drop image/link targets, keep the text
  const sentences = text.split(/(?<=[.!?])\s+|\n+/).map((s) => s.trim()).filter((s) => s.length > 20);
  const keep = sentences.filter((s) => ROAD.test(s) && (DIST.test(s) || /\broad|causeway|highway/i.test(s)));
  if (!keep.length) continue;
  hits += keep.length;
  out.push(`\n## ${f.replace(/\.md$/, '')}\n`, ...keep.map((s) => `- ${s}`));
}
writeFileSync(`${DIR}/_roads.md`, out.join('\n') + '\n');
console.log(`${hits} sentences`);
