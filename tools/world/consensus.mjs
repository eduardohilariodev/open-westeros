// Generates src/world-data.ts: every named place on the vector map, positioned by the consensus of the two source maps.
// A place is where the political atlas draws it (the vector map comes from it), or where the painted map has it if only that does.
// Usage: node tools/world/consensus.mjs   (reads tools/world/places.raw.txt)
import { writeFileSync } from 'node:fs';
import { SITES } from '../../src/config.ts';
import { at, atlasAt, rows } from './georef.mjs';

const siteKind = Object.fromEntries(Object.values(SITES).map((s) => [s.name, s.kind])); // the zoomable places carry their site's kind
const out = rows.map((e) => {
  const { lat, lon } = e.a ? atlasAt(e.a) : at(e.p);
  return [e.name, siteKind[e.name] ?? e.kind, +lat.toFixed(2), +lon.toFixed(2)];
});

writeFileSync('src/world-data.ts', `// Generated by tools/world/consensus.mjs from tools/world/places.raw.txt — do not edit by hand.
/** [name, kind, lat, lon] */
export const PLACES: [string, string, number, number][] = ${JSON.stringify(out).replace(/\],\[/g, '],\n  [')};
`);
console.log(`${out.length} places`);
