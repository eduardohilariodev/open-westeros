// Aligns the two source maps to a consensus and generates src/world-data.ts.
// Common frame = painted-map pixels (the outline map is registered to it by KNOWN_WORLD.outline). The political atlas is
// registered to the outline's coasts by tools/world/align-atlas.mjs (ATLAS_MAP.toPainted). Each map has its own
// georeference: the painted map from the Wall->Dorne distance (config.ts), the atlas from the latitude ticks printed on
// its margin. The globe uses the average of the two georeferences for all textures, so neither map is favoured. Place icons
// sit where the map being shown has them.
// Usage: node tools/world/consensus.mjs   (reads tools/world/places.raw.txt, writes src/world-data.ts)
import { writeFileSync } from 'node:fs';
import { ATLAS_MAP as M, KNOWN_WORLD as K, METRES_PER_DEGREE, MILE } from '../../src/config.ts';
import { readPlaces } from './places-table.mjs';

const rad = (d) => (d * Math.PI) / 180;
const T = M.toPainted; // atlasPx -> paintedPx, per axis
const toPainted = ([x, y]) => [T.scaleX * x + T.offsetX, T.scaleY * y + T.offsetY];
const rows = readPlaces();
const KING = rows.find((e) => e.name === "King's Landing"); // the 0° meridian city, on both maps

// Native georeferences as lat = a*y + b, lon = c*x + d over painted px.
const painted = (() => {
  const perDeg = (K.dorneCoast.y - K.castleBlack.y) / ((K.wallToDorneMiles * MILE) / METRES_PER_DEGREE);
  const perLon = perDeg * Math.cos(rad(K.castleBlack.lat - (KING.p[1] - K.castleBlack.y) / perDeg));
  return { a: -1 / perDeg, b: K.castleBlack.lat + K.castleBlack.y / perDeg, c: 1 / perLon, d: -KING.p[0] / perLon };
})();
const atlas = (() => {
  const EQUATOR = 7663, PER_DEG = 87.23; // measured from the margin ticks (10° = 872.3 px)
  const perLon = PER_DEG * Math.cos(rad((EQUATOR - KING.a[1]) / PER_DEG));
  const [ka] = KING.a;
  // lat = (EQUATOR - ya)/PER_DEG with ya = (yp - ty)/sy ; lon = (xa - ka)/perLon with xa = (xp - tx)/sx
  return { a: -1 / (PER_DEG * T.scaleY), b: (EQUATOR + T.offsetY / T.scaleY) / PER_DEG, c: 1 / (perLon * T.scaleX), d: -(T.offsetX / T.scaleX + ka) / perLon };
})();
const mean = (k) => (painted[k] + atlas[k]) / 2;
const G = { latPerPx: mean('a'), lat0: mean('b'), lonPerPx: mean('c'), lon0: mean('d') };
// King's Landing stays on the 0° meridian.
const kingPx = [(KING.p[0] + toPainted(KING.a)[0]) / 2, (KING.p[1] + toPainted(KING.a)[1]) / 2];
G.lon0 -= G.lonPerPx * kingPx[0] + G.lon0;

const at = ([x, y]) => ({ lat: G.latPerPx * y + G.lat0, lon: G.lonPerPx * x + G.lon0 });
// Icons sit on the map being shown: painted/outline styles use the painted position, the political style the atlas one
// (both through the common georeference, so every style overlays the others). Only places on both maps carry two positions.
const out = rows.filter((e) => e.kind !== 'site').map((e) => {
  const q = at(e.p ?? toPainted(e.a)), r = e.p && e.a ? at(toPainted(e.a)) : q;
  const row = [e.name, e.kind, +q.lat.toFixed(2), +q.lon.toFixed(2)];
  return Math.abs(r.lat - q.lat) + Math.abs(r.lon - q.lon) > 0.01 ? [...row, +r.lat.toFixed(2), +r.lon.toFixed(2)] : row;
});

const r6 = (v) => +v.toPrecision(8);
// The atlas texture lives in its own pixel frame: compose with the registration.
const ATLAS_G = {
  latPerPx: G.latPerPx * T.scaleY, lat0: G.latPerPx * T.offsetY + G.lat0,
  lonPerPx: G.lonPerPx * T.scaleX, lon0: G.lonPerPx * T.offsetX + G.lon0,
};
writeFileSync('src/world-data.ts', `// Generated by tools/world/consensus.mjs from tools/world/places.raw.txt — do not edit by hand.
// lat = latPerPx * y + lat0, lon = lonPerPx * x + lon0, where x/y are pixels of the source map.
export const PAINTED_FIT = { latPerPx: ${r6(G.latPerPx)}, lat0: ${r6(G.lat0)}, lonPerPx: ${r6(G.lonPerPx)}, lon0: ${r6(G.lon0)} };
export const ATLAS_FIT = { latPerPx: ${r6(ATLAS_G.latPerPx)}, lat0: ${r6(ATLAS_G.lat0)}, lonPerPx: ${r6(ATLAS_G.lonPerPx)}, lon0: ${r6(ATLAS_G.lon0)} };

/** [name, kind, lat, lon, atlasLat?, atlasLon?] — where the painted/outline maps have it, and (if different) the political atlas. */
export const PLACES: [string, string, number, number, number?, number?][] = ${JSON.stringify(out).replace(/\],\[/g, '],\n  [')};
`);

// Report: how well do the two drawings agree, and how far are the sites from their places on the atlas?
const f1 = (v) => v.toFixed(1), kmPerPx = (METRES_PER_DEGREE * Math.abs(G.latPerPx)) / 1000;
const both = rows.filter((e) => e.p && e.a);
const dist = (e) => Math.hypot(...[0, 1].map((i) => toPainted(e.a)[i] - e.p[i])) * kmPerPx;
const sorted = both.filter((e) => !['ocean', 'sea', 'region', 'mountain', 'forest', 'wild'].includes(e.kind)).map(dist).sort((a, b) => a - b);
console.log(`places: ${rows.length - 2}, on both maps: ${both.length - 2}; generated ${out.length}`);
console.log(`painted vs political position of the same point places (km): median ${f1(sorted[sorted.length >> 1])}, 90% ${f1(sorted[Math.floor(sorted.length * 0.9)])}, max ${f1(sorted.at(-1))}`);
console.log('km per painted px', kmPerPx.toFixed(2), '| native lat slope painted', f1(1 / -painted.a), 'px/deg, atlas', f1(1 / -atlas.a), 'px/deg (in painted px)');
for (const n of ["King's Landing", 'Winterfell']) { const e = rows.find((r) => r.name === n); console.log(`${n}: painted ${e.p.map(Math.round)} political->painted ${toPainted(e.a).map(Math.round)}`); }
for (const e of [...both].sort((x, y) => dist(y) - dist(x)).slice(0, 12)) console.log(`  far apart: ${e.name.padEnd(30)} ${f1(dist(e))} km`);
