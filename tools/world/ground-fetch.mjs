// Ground materials from Poly Haven (CC0), for the close-up land shading in src/globe/ground.ts.
// `npm run ground` downloads each material's diffuse and GL normal map, re-encodes them as 1k and 512 px JPGs in
// public/textures/ground/ and writes manifest.json: the real size of one tile in metres, its mean colour (the shader
// uses diffuse / mean as a detail layer over the baked biome colour) and its authors for the credits.
// Poly Haven asks for a clear credit and a unique User-Agent: see index.html (#credits) and CREDITS.md.
import sharp from 'sharp';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';

const OUT = 'public/textures/ground', API = 'https://api.polyhaven.com', UA = { 'User-Agent': 'OpenWesteros/1.0 (open-source map)' };

// id: [environment, role]. Environments are what the shader's groundClass() picks between; roles say how a material is used
// inside one (the first of an environment is its main ground, the second its variant, the third its rough/steep face).
// Order is the layer index in the texture arrays: keep it in step with GROUND in src/globe/ground.ts.
export const MATERIALS = [
  ['snow_02', 'snow', 'fresh snow'],
  ['snow_field_aerial', 'snow', 'wind-worn snowfield'],
  ['snow_03', 'snow', 'dirty snow'],
  ['forrest_ground_03', 'forest', 'pine needles'],
  ['forest_leaves_02', 'forest', 'mossy floor'],
  ['dirt_floor', 'forest', 'forest soil'],
  ['rock_boulder_dry', 'rock', 'boulders'],
  ['dark_rock', 'rock', 'layered dark rock'],
  ['aerial_rocks_02', 'rock', 'rock faces'],
  ['rocky_terrain', 'rock', 'scree'],
  ['leafy_grass', 'grass', 'lush grass'],
  ['grass_ground', 'grass', 'dry grass'],
  ['sparse_grass', 'grass', 'sparse grass'],
  ['farm_soil', 'farm', 'tilled soil'],
  ['sandy_gravel', 'farm', 'gravel'],
  ['mud_forest', 'wet', 'wet mud'],
  ['brown_mud_leaves_01', 'wet', 'sodden leaves'],
  ['red_sand', 'desert', 'red sand'],
  ['cracked_red_ground', 'desert', 'cracked clay'],
  ['sandstone_cracks', 'desert', 'sandstone'],
  ['aerial_beach_01', 'coast', 'beach sand'],
  ['large_pebbles', 'coast', 'pebbles'],
  ['seaside_rock', 'coast', 'shore rock'],
  ['burned_ground_01', 'volcanic', 'ash and cinder'],
  ['dark_rock_02', 'volcanic', 'black rock'],
];

const json = async (url) => { const r = await fetch(url, { headers: UA }); if (!r.ok) throw new Error(`${url}: ${r.status}`); return r.json(); };
const bytes = async (url) => { const r = await fetch(url, { headers: UA }); if (!r.ok) throw new Error(`${url}: ${r.status}`); return Buffer.from(await r.arrayBuffer()); };
const jpg = (img, size, q) => img.clone().resize(size, size, { fit: 'fill' }).jpeg({ quality: q, mozjpeg: true }).toBuffer();

async function main() {
  mkdirSync(OUT, { recursive: true });
  const manifest = [];
  for (const [id, env, role] of MATERIALS) {
    const [info, files] = await Promise.all([json(`${API}/info/${id}`), json(`${API}/files/${id}`)]);
    const diff = sharp(await bytes(files.Diffuse['1k'].jpg.url)), nor = sharp(await bytes(files.nor_gl['1k'].jpg.url));
    const { channels } = await diff.clone().stats();
    for (const [name, img, q] of [['diff', diff, 80], ['nor', nor, 78]]) {
      for (const size of [512]) {
        const file = `${OUT}/${id}_${name}_512.jpg`;
        writeFileSync(file, await jpg(img, size, q));
      }
    }
    manifest.push({
      id, env, role, name: info.name,
      metres: +(info.dimensions[0] / 1000).toFixed(2),
      mean: channels.slice(0, 3).map((c) => +(c.mean / 255).toFixed(4)),
      authors: Object.keys(info.authors),
      url: `https://polyhaven.com/a/${id}`,
    });
    console.log(id.padEnd(22), env.padEnd(9), `${manifest.at(-1).metres} m`, manifest.at(-1).authors.join(', '));
  }
  writeFileSync(`${OUT}/manifest.json`, JSON.stringify(manifest, null, 1) + '\n');
  const authors = [...new Set(manifest.flatMap((m) => m.authors))].sort();
  writeFileSync(`${OUT}/CREDITS.md`, [
    '# Ground textures',
    '',
    'All materials are from [Poly Haven](https://polyhaven.com), released under CC0. Poly Haven asks for a clear credit.',
    `Artists: ${authors.join(', ')}.`,
    '',
    ...manifest.map((m) => `- [${m.name}](${m.url}) by ${m.authors.join(', ')}`),
    '',
    'Generated by `npm run ground` (tools/world/ground-fetch.mjs).',
    '',
  ].join('\n'));
  console.log(`${manifest.length} materials, ${authors.length} artists`);
}
if (import.meta.url === `file:///${process.argv[1]?.replace(/\\/g, '/')}`) await main();
