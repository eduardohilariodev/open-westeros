import {chromium} from 'playwright-core';
const b=await chromium.launch({channel:'chrome',args:['--use-gl=angle','--enable-unsafe-swiftshader']});
const p=await (await b.newContext({viewport:{width:1280,height:760}})).newPage();
p.on('console',m=>{if(['warning','error'].includes(m.type()))console.log(m.type(),m.text().slice(0,300))});
p.on('pageerror',e=>console.log('ERR',e.message));
p.on('requestfailed',r=>console.log('FAILED',r.url().slice(-60)));
p.on('response',r=>{if(r.status()>=400)console.log(r.status(),r.url().slice(-70))});
await p.goto('http://localhost:5199');
await p.waitForSelector('#loading',{state:'detached',timeout:120000}).catch(()=>console.log('still loading'));
await p.waitForTimeout(3000);
console.log(await p.evaluate(()=>[document.getElementById('reliefBtn').getAttribute('aria-pressed'),document.querySelector('#loadMsg')?.textContent]));
await p.screenshot({path:process.argv[2]+'g.png'});
await b.close();
